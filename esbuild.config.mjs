// Build for the Review plugin (fork). Replaces the original rollup + ES5 build.
//
// Why: Obsidian 1.15 ships Plugin, Modal and PluginSettingTab as native JS classes. An ES5 build turns
// `class X extends Plugin` into `__extends` + `_super.apply(this, arguments)`, which throws
// "Class constructor Plugin cannot be invoked without 'new'" and the plugin never loads.
// Targeting ES2018+ keeps the classes native.
import esbuild from "esbuild";
import builtins from "builtin-modules";

const prod = process.argv[2] === "production";

const ctx = await esbuild.context({
  banner: { js: "/*\nTHIS IS A GENERATED/BUNDLED FILE BY ESBUILD\nif you want to view the source, visit the plugin's GitHub repository\n*/\n" },
  entryPoints: ["main.ts"],
  bundle: true,
  external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtins],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await ctx.rebuild();
  await ctx.dispose();
} else {
  await ctx.watch();
}
